import { test, expect } from '@playwright/test';
import { login } from './auth';

test('permission group adoption previews before changes and readonly identities stay outside grants', async ({ page }) => {
  await login(page);
  await page.goto('/system-groups');
  await expect(page.getByRole('heading', { name: 'Linux 权限组', exact: true })).toBeVisible();
  await expect(page.getByRole('row').filter({ has: page.getByText('human', { exact: true }) })).toHaveCount(0);
  await expect(page.getByText('e2e-project-group', { exact: true })).toHaveCount(0);
  await page.getByRole('combobox', { name: '权限组范围' }).focus();
  await page.getByRole('combobox', { name: '权限组范围' }).press('ArrowDown');
  await page.getByText('其他组（只读）', { exact: true }).click();
  await page.getByRole('textbox', { name: '搜索权限组' }).fill('e2e-project-group');
  const existing = page.getByRole('row').filter({ has: page.getByText('e2e-project-group', { exact: true }) });
  await expect(existing.getByRole('button', { name: /编\s*辑/ })).toHaveCount(0);
  await existing.getByRole('button', { name: '启用管理' }).click();
  await expect(page.getByRole('button', { name: '确认执行' })).toBeDisabled();
  const before = (await (await page.request.get('/api/system-groups?scope=other')).json()).find((g: any) => g.name === 'e2e-project-group');
  expect(before.managed).toBe(false);
  await page.getByLabel('操作原因').fill('browser adopt existing permission group');
  await page.getByRole('button', { name: '确认执行' }).click();
  await expect(page.getByText('请求已提交，以下为服务器返回结果')).toBeVisible();
  await page.getByRole('button', { name: /关\s*闭/ }).click();
  await page.getByRole('textbox', { name: '搜索权限组' }).clear();
  const human = page.getByRole('row').filter({ has: page.getByText('human', { exact: true }) });
  await expect(human.getByRole('button', { name: /编\s*辑/ })).toHaveCount(0);
  await expect(human.getByRole('button', { name: '启用管理' })).toHaveCount(0);
  const alice = page.getByRole('row').filter({ has: page.locator('td').getByText('alice', { exact: true }) }).first();
  await expect(alice.getByRole('button', { name: /编\s*辑/ })).toHaveCount(0);
  await expect(alice.getByText('私有主组', { exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: '权限组范围' }).focus();
  await page.getByRole('combobox', { name: '权限组范围' }).press('ArrowDown');
  await page.getByText('受管权限组', { exact: true }).click();
  await expect(existing.getByRole('button', { name: /编\s*辑/ })).toBeEnabled();
  await page.getByRole('button', { name: '创建普通权限组' }).click();
  await page.getByLabel('权限组名').fill('e2e-created-permission');
  await page.getByRole('button', { name: /保\s*存/ }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const created = page.getByRole('row').filter({ has: page.getByText('e2e-created-permission', { exact: true }) });
  await expect(created.getByRole('button', { name: /编\s*辑/ })).toBeEnabled();
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.locator('.ant-table-content').evaluate(element => { element.scrollLeft = 0; });
  await expect(created.getByRole('button', { name: /编\s*辑/ })).toBeInViewport({ ratio: 1 });
  await expect(created.getByRole('button', { name: '删除空组' })).toBeInViewport({ ratio: 1 });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.locator('.ant-table-content').evaluate(element => { element.scrollLeft = 0; });
  await expect(created.getByRole('button', { name: /编\s*辑/ })).toBeInViewport({ ratio: 1 });
  await expect(created.getByRole('button', { name: '删除空组' })).toBeInViewport({ ratio: 1 });
  await created.getByRole('button', { name: /编\s*辑/ }).click();
  await page.getByLabel('权限组名').fill('e2e-renamed-permission');
  const editPreview = page.waitForRequest(request => request.url().endsWith('/change-preview') && request.method() === 'POST');
  await page.getByRole('button', { name: /保\s*存/ }).click();
  const previewBody = (await editPreview).postDataJSON();
  expect(previewBody.changes).toEqual({ name: 'e2e-renamed-permission', members: [] });
  expect(previewBody.revision).toBeGreaterThan(0);
  await page.getByLabel('操作原因').fill('browser rename permission group');
  await page.getByRole('button', { name: '确认执行' }).click();
  await expect(page.getByText('请求已提交，以下为服务器返回结果')).toBeVisible();
  await page.getByRole('button', { name: /关\s*闭/ }).click();
  await expect(page.getByText('e2e-renamed-permission', { exact: true })).toBeVisible();
  const managed = await (await page.request.get('/api/system-groups?scope=managed')).json();
  expect(managed.every((g: any) => g.assignable === true && g.kind === 'permission')).toBe(true);

  await page.goto('/accounts');
  await page.getByRole('button', { name: '创建账号' }).click();
  await page.getByLabel('普通附属系统组').click();
  await expect(page.locator('.ant-select-item-option[title="e2e-project-group"]')).toBeVisible();
  await expect(page.locator('.ant-select-item-option[title="human"]')).toHaveCount(0);
  await expect(page.locator('.ant-select-item-option[title="alice"]')).toHaveCount(0);
  await page.locator('.ant-select-item-option[title="e2e-project-group"]').click();
  await page.keyboard.press('Escape');
  await page.getByLabel('用户名').fill('e2e-group-user');
  await page.getByLabel('初始密码').fill('Strong-group-user-pass-42');
  const create = page.waitForRequest(request => request.url().endsWith('/api/system-users') && request.method() === 'POST');
  await page.getByRole('button', { name: /保\s*存/ }).click();
  expect((await create).postDataJSON().groups).toEqual(['e2e-project-group']);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const accounts = await (await page.request.get('/api/system-users?scope=human&state=active')).json();
  const user = accounts.find((a: any) => a.username === 'e2e-group-user');
  expect(user.groups).toContain('human');
  expect(user.groups).toContain('e2e-project-group');
  expect(user.private_group).toBe('e2e-group-user');
});
