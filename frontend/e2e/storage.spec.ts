import {test,expect} from '@playwright/test';
import {login} from './auth';

test('shared project create preview, notes edit, members and bilingual narrow layout',async({page})=>{
 await login(page);
 await page.clock.install();
 let previews=0;page.on('request',request=>{if(request.url().includes('/shares') && request.url().endsWith('/change-preview'))previews++;});
 const users=await(await page.request.get('/api/system-users?scope=human')).json();
 const member=users.find((a:any)=>a.managed && a.is_human && !a.protected && a.status==='active');
 expect(member).toBeTruthy();
 await page.goto('/shares');
 await page.getByRole('button',{name:'创建共享项目'}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('项目名').fill('storage-browser-project');
 await dialog.getByRole('combobox',{name:'选择共享成员'}).click();
 await page.getByText(member.username,{exact:true}).last().click();
 await dialog.getByRole('button',{name:'添加成员'}).click();
 await dialog.getByText('读写',{exact:true}).click();
 await expect(dialog.getByRole('radio',{name:'读写',exact:true})).toBeChecked();
 await dialog.getByLabel('备注').fill('shared experiment data');
 await dialog.getByRole('button',{name:/保\s*存/}).click();
 await expect(page.getByRole('dialog')).toHaveCount(1);
 await page.getByLabel('操作原因').fill('test shared project creation');
 await page.getByRole('button',{name:'确认执行'}).click();
 await expect(page.getByText('请求已提交，以下为服务器返回结果')).toBeVisible();
 await expect(page.locator('.ant-alert-error')).toHaveCount(0);
 await page.clock.fastForward(31000);
 await expect(page.getByText('预览已过期，请重新预览后再确认。',{exact:true})).toHaveCount(0);
 await expect(page.locator('.ant-alert-error')).toHaveCount(0);
 expect(previews).toBe(1);
 await page.clock.setSystemTime(new Date());
 await page.getByRole('button',{name:/关\s*闭/}).click();
 await page.getByRole('textbox',{name:'搜索共享项目'}).fill('storage-browser-project');
 const row=page.getByRole('row').filter({has:page.getByText('storage-browser-project',{exact:true})});
 await row.getByRole('button',{name:'查看访问成员'}).click();
 await expect(page.getByRole('dialog',{name:/项目访问成员/})).toBeVisible();
 await expect(page.getByLabel('项目访问成员').getByText('shared experiment data',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:/关\s*闭/}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await row.getByRole('button',{name:'编辑授权'}).click();
 await page.getByLabel('备注').fill('updated notes');
 await page.getByRole('button',{name:/保\s*存/}).click();
 await page.getByLabel('操作原因').fill('test notes edit');
 await page.getByRole('button',{name:'确认执行'}).click();
 await expect(page.getByText('请求已提交，以下为服务器返回结果')).toBeVisible();
 await page.getByRole('button',{name:/关\s*闭/}).click();
 await page.reload();
 await page.getByRole('textbox',{name:'搜索共享项目'}).fill('storage-browser-project');
 await page.getByRole('button',{name:'查看访问成员'}).click();
 await expect(page.getByText('updated notes',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:/关\s*闭/}).click();
 await page.locator('.language-select').click();await page.getByText('English',{exact:true}).last().click();
 await page.getByRole('button',{name:'View access members'}).click();
 await expect(page.getByLabel('Project access members').getByText('Read/write',{exact:true})).toBeVisible();
 await page.setViewportSize({width:375,height:812});
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
 await page.screenshot({path:'test-results/storage-shares-mobile.png',animations:'disabled',fullPage:true});
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.goto('/storage');
 await expect(page.getByRole('textbox',{name:'Search users'})).toBeVisible();
 await expect(page.getByRole('columnheader',{name:'Files',exact:true})).toHaveCount(0);
 const refreshResponse=page.waitForResponse(response=>response.url().endsWith('/api/storage/refresh') && response.request().method()==='POST');
 await page.getByRole('button',{name:'Refresh directory usage'}).click();
 expect((await refreshResponse).ok()).toBe(true);
 await expect(page.getByRole('status').filter({hasText:'Last directory measurement:'})).not.toContainText('—');
 await expect(page.getByRole('button',{name:'Refresh directory usage'})).toBeEnabled();
 await expect(page.getByText('Available space',{exact:true}).first()).toBeVisible();
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
});
