import {test,expect} from '@playwright/test';
import {login} from './auth';

test('residual reminder and waiting duration persist while invalid required waits cannot save',async({page})=>{
  await login(page);
  await page.goto('/settings');
  await page.getByRole('button',{name:'编辑策略',exact:true}).click();
  const defaults=page.getByRole('group',{name:'默认残留等待时间',exact:true});
  await expect(defaults.getByRole('button',{name:'不限时',exact:true})).toHaveCount(0);
  for(const name of ['小时','分钟','秒'])await defaults.getByRole('spinbutton',{name,exact:true}).fill('0');
  await page.getByRole('button',{name:/保\s*存/}).click();
  await expect(page.getByText('残留等待时间需为1秒至24小时',{exact:true})).toBeVisible();
  await defaults.getByRole('button',{name:'1分钟',exact:true}).click();
  await page.getByLabel('默认残留提醒').click();
  await page.getByRole('button',{name:/保\s*存/}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect(await (await page.request.get('/api/settings')).json()).toMatchObject({default_orphan_reminder:false,default_orphan_wait_seconds:60});
  await page.reload();
  await page.getByRole('button',{name:'编辑策略',exact:true}).click();
  await expect(page.getByLabel('默认残留提醒')).toHaveAttribute('aria-checked','false');
  await expect(page.getByRole('group',{name:'默认残留等待时间',exact:true}).getByRole('spinbutton',{name:'分钟',exact:true})).toHaveValue('1');
  await page.getByRole('button',{name:/取\s*消/}).click();

  await page.goto('/tasks/e2e-residual-task');
  await page.getByRole('button',{name:'编辑策略',exact:true}).click();
  await expect(page.getByText('自动清理已确认残留 worker',{exact:true})).toHaveCount(0);
  const wait=page.getByRole('group',{name:'残留等待时间',exact:true});
  await wait.getByRole('button',{name:'1分钟',exact:true}).click();
  await page.getByLabel('残留提醒',{exact:true}).click();
  await page.getByRole('button',{name:/保\s*存/}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'终止残留进程',exact:true})).toHaveCount(0);
  expect(await (await page.request.get('/api/tasks/e2e-residual-task')).json()).toMatchObject({orphan_reminder:false,orphan_wait_seconds:60,status:'finalizing'});
  await page.reload();
  await page.getByRole('button',{name:'编辑策略',exact:true}).click();
  await expect(page.getByLabel('残留提醒',{exact:true})).toHaveAttribute('aria-checked','false');
  await expect(page.getByRole('group',{name:'残留等待时间',exact:true}).getByRole('spinbutton',{name:'分钟',exact:true})).toHaveValue('1');
  await page.getByLabel('残留提醒',{exact:true}).click();
  await page.getByRole('button',{name:/保\s*存/}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'终止残留进程',exact:true})).toBeVisible();
  await page.setViewportSize({width:375,height:812});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await expect.poll(()=>page.locator('.content-scroll').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  for(const name of ['编辑策略','终止残留进程','终止整个任务'])await expect.poll(()=>page.getByRole('button',{name,exact:true}).evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=window.innerWidth;})).toBe(true);
  await page.evaluate(()=>{
    localStorage.setItem('gpupm.locale','en-US');
    window.dispatchEvent(new StorageEvent('storage',{key:'gpupm.locale',newValue:'en-US'}));
  });
  await expect(page.getByRole('button',{name:'Terminate residual processes',exact:true})).toBeVisible();
  await expect.poll(()=>page.locator('.content-scroll').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  for(const name of ['Edit policy','Terminate residual processes','Terminate entire task'])await expect.poll(()=>page.getByRole('button',{name,exact:true}).evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=window.innerWidth;})).toBe(true);
});

test('active tasks retain a waiting worker and manual residual confirmation terminates exactly its previewed identity',async({page})=>{
  await login(page);
  const before=await Promise.all(['demo-task-1','demo-task-2'].map(async id=>(await page.request.get(`/api/tasks/${id}`)).json()));
  const residual=await (await page.request.get('/api/tasks/e2e-residual-task')).json();
  expect(residual.status).toBe('awaiting_cleanup');
  let executions=0;
  page.on('request',r=>{if(r.url().endsWith('/terminate')&&r.method()==='POST')executions++;});
  await page.goto('/tasks');
  await expect(page.getByRole('combobox',{name:'状态筛选',exact:true})).toBeVisible();
  await expect(page.getByText('全部进行中任务',{exact:true})).toBeVisible();
  const row=page.getByRole('row').filter({has:page.getByRole('link',{name:'E2E residual worker',exact:true})});
  await expect(row.getByText('待清理',{exact:true})).toBeVisible();
  await expect(row.getByText('主进程已退出，残留进程等待人工处理',{exact:true})).toBeVisible();
  await row.getByRole('button',{name:'终止残留进程',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await expect(dialog.getByRole('cell',{name:'990001',exact:true})).toBeVisible();
  await expect(dialog.getByRole('cell',{name:'python DataLoader worker',exact:true})).toBeVisible();
  await expect(dialog.getByRole('cell').filter({hasText:'e2e-residual-boot'})).toContainText('99000100');
  await expect(dialog.getByRole('columnheader',{name:'运行时间',exact:true})).toBeVisible();
  await expect(dialog.getByRole('button',{name:'确认终止',exact:true})).toBeDisabled();
  await page.setViewportSize({width:375,height:812});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await expect.poll(()=>dialog.locator('.ant-modal-body').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await expect(dialog.getByRole('button',{name:'Close',exact:true})).toBeInViewport();
  await expect(dialog.getByRole('button',{name:'确认终止',exact:true})).toBeInViewport();
  await dialog.getByRole('button',{name:/取\s*消/}).click();
  await page.setViewportSize({width:1280,height:720});
  expect(executions).toBe(0);
  expect((await (await page.request.get('/api/tasks/e2e-residual-task')).json()).members).toEqual(residual.members);
  await row.getByRole('button',{name:'终止残留进程',exact:true}).click();
  await expect(dialog.getByRole('button',{name:'确认终止',exact:true})).toBeDisabled();
  await dialog.getByLabel('终止原因',{exact:true}).fill('E2E manually confirmed residual worker');
  await dialog.getByRole('button',{name:'确认终止',exact:true}).click();
  await expect(dialog.getByText('请求已提交，以下为服务器返回结果',{exact:true})).toBeVisible();
  await expect(dialog.locator('.ant-alert-error')).toHaveCount(0);
  await expect(dialog.getByText('成功',{exact:true})).toBeVisible();
  await dialog.getByRole('button',{name:/关\s*闭/}).click();
  await expect(page.getByRole('link',{name:'E2E residual worker',exact:true})).toHaveCount(0);
  expect(executions).toBe(1);
  expect(await (await page.request.get('/api/tasks/e2e-residual-task')).json()).toMatchObject({status:'finished',members:[],finalizing_since:null});
  for(const original of before){
    const after=await (await page.request.get(`/api/tasks/${original.id}`)).json();
    expect(after.members).toEqual(original.members);
    expect(after.status).toBe(original.status);
  }
});
