import {test,expect} from '@playwright/test';
import {login} from './auth';
test('GPU filters reset together and make hidden finished tasks discoverable',async({page})=>{
 await login(page);
 const device=(await(await page.request.get('/api/gpus')).json()).items[0];
 await page.goto('/tasks');
 await page.getByRole('combobox',{name:'GPU 筛选',exact:true}).focus();
 await page.getByRole('combobox',{name:'GPU 筛选',exact:true}).press('ArrowDown');
 const filtered=page.waitForResponse(r=>r.url().includes('/api/tasks?')&&new URL(r.url()).searchParams.get('gpu')===device.uuid);
 await page.getByText(`GPU ${device.index} · ${device.name}`,{exact:true}).last().click();
 expect((await filtered).ok()).toBe(true);
 await expect(page.locator('tr.ant-table-row').first()).toBeVisible();
 await expect(page.getByRole('columnheader',{name:'使用过的 GPU'})).toBeVisible();
 await page.getByRole('combobox',{name:'用户筛选',exact:true}).focus();
 await page.getByRole('combobox',{name:'用户筛选',exact:true}).press('ArrowDown');
 await page.locator('.ant-select-item-option-content').getByText('alice',{exact:true}).click();
 await page.getByRole('combobox',{name:'任务范围',exact:true}).focus();
 await page.getByRole('combobox',{name:'任务范围',exact:true}).press('ArrowDown');
 await page.getByText('其他账号（只读）',{exact:true}).last().click();
 await expect(page.locator('.filters')).not.toContainText('alice');
 await page.getByRole('button',{name:'重置筛选',exact:true}).click();
 await expect(page.locator('.filters')).not.toContainText(device.name);
 await page.getByRole('combobox',{name:'状态筛选',exact:true}).focus();
 await page.getByRole('combobox',{name:'状态筛选',exact:true}).press('ArrowDown');
 await page.getByText('已结束',{exact:true}).last().click();
 await expect(page.getByText('当前筛选条件下没有任务',{exact:true})).toBeVisible();
 await expect(page.getByText(/旧任务未保留设备信息时/)).toBeVisible();
 await page.getByRole('button',{name:'清除筛选，查看全部任务',exact:true}).click();
 await expect(page.locator('tr.ant-table-row').first()).toBeVisible();
 await page.setViewportSize({width:375,height:812});
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
 await page.locator('.language-select').click();await page.getByText('English',{exact:true}).last().click();
 await expect(page.getByRole('button',{name:'Reset filters',exact:true})).toBeVisible();
 await expect(page.getByText('HTTP 422')).toHaveCount(0);
 await page.screenshot({path:'test-results/task-filters-mobile.png',fullPage:true});
});
